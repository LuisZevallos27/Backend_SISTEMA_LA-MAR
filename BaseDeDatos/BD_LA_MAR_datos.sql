-- 3) Insumos con stock negativo (debe salir VACIO)
SELECT i.nombre_insumo,
       COALESCE((SELECT SUM(da.cantidad) FROM Detalle_Abastecimiento da JOIN Abastecimiento a ON a.id_abastecimiento = da.id_abastecimiento
                  WHERE da.id_insumo = i.id_insumo AND a.estado = 'Recibido'), 0)
     - COALESCE((SELECT SUM(dp.cantidad * r.cantidad_usada) FROM Detalle_Pedido dp JOIN Pedido p ON p.id_pedido = dp.id_pedido
                   JOIN Receta_Insumo r ON r.id_plato = dp.id_plato WHERE r.id_insumo = i.id_insumo AND p.estado_pedido <> 'Anulado'), 0) AS stock
  FROM Insumo i
 WHERE COALESCE((SELECT SUM(da.cantidad) FROM Detalle_Abastecimiento da JOIN Abastecimiento a ON a.id_abastecimiento = da.id_abastecimiento
                  WHERE da.id_insumo = i.id_insumo AND a.estado = 'Recibido'), 0)
     < COALESCE((SELECT SUM(dp.cantidad * r.cantidad_usada) FROM Detalle_Pedido dp JOIN Pedido p ON p.id_pedido = dp.id_pedido
                   JOIN Receta_Insumo r ON r.id_plato = dp.id_plato WHERE r.id_insumo = i.id_insumo AND p.estado_pedido <> 'Anulado'), 0);

